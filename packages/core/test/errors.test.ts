import { describe, expect, it } from "vitest"
import { HannamSyntaxError, compile } from "../src/index.js"

function errorOf(source: string): HannamSyntaxError {
  try {
    compile(source, { filename: "t.hn" })
  } catch (e) {
    if (e instanceof HannamSyntaxError) return e
    throw e
  }
  throw new Error(`에러가 나야 하는데 변환됐습니다:\n${source}`)
}

describe("컴파일 에러", () => {
  it.each([
    ["물음표 4개", "예???? x {\n}", "물음표는 1~3개", 1],
    ["아뇨 2번", "요이~ x 목록 {\n  아뇨아뇨\n}", "1번(continue) 또는 4번(else)", 2],
    ["if 없는 예??", "엄. a = 1\n예?? a {\n}", "'예??'(else if)", 2],
    ["if 없는 else", "아뇨아뇨아뇨아뇨 {\n}", "'아뇨아뇨아뇨아뇨'(else)", 1],
    ["else 뒤 예??", "예? a {\n} 아뇨아뇨아뇨아뇨 {\n} 예?? b {\n}", "'예??'(else if)", 3],
    ["무슨 발언이세요? 괄호 붙임", '무슨 발언이세요?("a")', "띄어 쓰고", 1],
    ["무슨 발언이세요? 쉼표 괄호", "무슨 발언이세요? (a, b)", "쉼표로 여러 값", 1],
    ["confirm 문장에 블록", '예? 무슨 발언이세요?("q") {\n}', "'예? 예? 무슨 발언이세요?", 1],
    ["confirm 괄호 없음", '엄.. a = 예? 무슨 발언이세요? "q"', "괄호로 질문", 1],
    ["말줄임표 주석", "엄… 주석", "마침표 3개", 1],
    ["말줄임표 throw", '아… 줴줴이야… "x"', "마침표 3개", 1],
    ["둥근 따옴표", "엄.. a = “x”", "둥근 따옴표", 1],
    ["호 3개 클래스", "오호호호~ A {\n}", "'오호호호호~'", 1],
    ["extends 키워드", "오호호호호~ A extends B {\n}", "'오호호호홋~ 이름 부모 {'", 1],
    ["부모 없는 상속", "오호호호홋~ A {\n}", "부모 클래스", 1],
    ["이 2개 반복", "요이이~ x {\n}", "반복문은", 1],
    ["물음표 없는 try", "진~지 {\n}", "'진~지?'", 1],
    ["try 없는 catch", "지~랄 e {\n}", "'지~랄'(catch)", 1],
    ["async 화살표", "엄.. f = 1\n티~원 (e) => {}", "화살표 함수", 2],
    ["default가 마지막이 아님", "예??? x {\n  아뇨아뇨아뇨아뇨 {\n  }\n  1 {\n  }\n}", "마지막", 4],
    ["switch 안 일반 문장", "예??? x {\n  무슨 발언이세요? 1\n}", "갈래만", 2],
    ["return 오타", "티-원 f() {\n  아! 줴줴이야 1\n}", "'아! 줴줴이야~'", 2],
    ["throw 값 없음", "아... 줴줴이야...", "던질 값", 1],
    ["엄 점 4개", "엄.... 주석", "3개까지", 1],
    ["닫히지 않은 블록", "예? a {\n  무슨 발언이세요? 1", "닫히지 않은", 1],
    ["break 뒤 값", "요이~ x 목록 {\n  줴줴이야 1\n}", "'줴줴이야'(break)", 2],
    ["범위 변수가 패턴", "요이~ [a] 0..3 {\n}", "이름 하나", 1],
    // 독립 리뷰 회귀
    ["M7 continue 뒤 else", "요이~ x 목록 {\n  예? a {\n  }\n  아뇨\n  아뇨아뇨아뇨아뇨 {\n  }\n}", "'아뇨아뇨아뇨아뇨'(else)", 5],
    ["M7 break 뒤 else if", "요이~ x 목록 {\n  예? a {\n  }\n  줴줴이야\n  예?? b {\n  }\n}", "'예??'(else if)", 5],
    ["L1 이름과 부모 붙여 씀", "오호호호홋~ A(B) {\n}", "띄어 씁니다", 1],
    ["L2 갈래 사이 세미콜론", "예??? x {\n  1 { a() }; 2 { b() }\n}", "';'", 2],
    ["L3 대상 값에 쉼표", "예??? a, b {\n}", "하나만", 1],
    ["L5 엄.. 붙여 씀", "엄..x = 1", "띄어 쓰고", 1],
    ["L5 템플릿 안 문장 키워드", "엄.. s = `${무슨 발언이세요? 1}`", "값 위치 키워드만", 1],
    ["L5 요히~ 범위", "요히~ k 0..3 {\n}", "'요이~'로", 1],
    ["L5 throw 점 2개", '아... 줴줴이야.. "x"', "'아... 줴줴이야...'", 1],
    ["L6 키워드 붙여 씀", "요이이이~(x) {\n}", "띄어 쓰고", 1],
    // 사이트 리뷰에서 발견: 명세상 에러인 변형
    ["물결 없는 catch", "진~지? {\n} 지랄 e {\n}", "'지~랄'", 2],
    ["하이픈 catch", "진~지? {\n} 지-랄 e {\n}", "'지~랄'", 2],
    ["물결 없는 try", "진지? {\n}", "'진~지?'", 1],
    ["물결 없는 클래스", "오호호호호 할일 {\n}", "물결까지", 1],
    ["콧 클래스", "오콧콧콧~ 할일 {\n}", "'오호호호호~'", 1],
    ["예약어 변수 아뇨", "엄.. 아뇨 = 1", "예약어", 1],
    ["예약어 변수 줴줴이야", "엄. 줴줴이야 = 1", "예약어", 1],
  ])("%s", (_, source, message, line) => {
    const e = errorOf(source)
    expect(e.message).toContain(message)
    expect(e.line).toBe(line)
    expect(e.filename).toBe("t.hn")
  })

  it("코드 조각의 ^는 한글을 두 칸으로 세어 위치를 맞춘다", () => {
    // "엄.. 목록 = 1; "의 화면 폭: 엄(2) + ".. "(3) + 목록(4) + " = 1; "(6) = 15
    const e = errorOf("엄.. 목록 = 1; 예???? 목록 {\n}")
    expect(e.frame).toBe(`1 | 엄.. 목록 = 1; 예???? 목록 {\n${" ".repeat("1 | ".length + 15)}^`)
  })

  it("rawMessage는 위치와 코드 조각이 없는 원래 문구다", () => {
    const e = errorOf("엄. a = 1\n예???? a {\n}")
    expect(e.rawMessage).not.toContain("t.hn:")
    expect(e.message.startsWith(e.rawMessage)).toBe(true)
    expect(e.rawMessage).toContain("물음표는 1~3개")
  })

  it("에러 메시지에 위치와 코드 조각이 들어간다", () => {
    const e = errorOf("엄. a = 1\n예???? a {\n}")
    expect(e.message).toContain("t.hn:2:1")
    expect(e.frame).toBe("2 | 예???? a {\n    ^")
  })
})
